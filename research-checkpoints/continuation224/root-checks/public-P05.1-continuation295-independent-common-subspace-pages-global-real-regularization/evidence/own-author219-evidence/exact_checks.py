#!/usr/bin/env python3
"""Own finite exact checks: fractions only, no external dependencies or shell."""
from fractions import Fraction as F
from itertools import product
import json,pathlib,math
P=pathlib.Path(__file__).resolve().parent
I=json.loads((P/'exact-check-input.json').read_text()); eta=F(I['eta'])
count=0
D=I['dual_grid_denominator']
for p1,p2 in product((F(j,D) for j in range(-D,D+1)),repeat=2):
 phi=abs(p2); b=-eta; psi=(1+eta)*abs(p2)-eta
 assert phi-eta<=psi<=phi and psi>=b
 # Explicit lower-hull representation at the same rational p1:
 t=abs(p2); height=t*1+(1-t)*(-eta)
 assert height==psi
 assert (1-t)*0+t*(1 if p2>=0 else -1)==p2
 if p2==0: assert psi==b
 count+=1
print(f'Dual grid: {count} points; hull bounds, source combination and every sampled fiber minimum exact.')
D=I['primal_grid_denominator'];R=I['primal_grid_radius'];count=0
for x,y in product((F(j,D) for j in range(-R*D,R*D+1)),repeat=2):
 f=abs(x)+max(F(0),abs(y)-1)
 A=abs(x)+eta+max(F(0),abs(y)-(1+eta))
 assert f<=A<=f+eta
 if y==0: assert A==abs(x)+eta
 count+=1
print(f'Primal grid: {count} points; f<=F<=f+eta and sampled whole-line trace formula exact.')
# Trace graph generated by vertex (0,eta) and exact lifted rays (+/-1,1).
for j in range(-32,33):
 x=F(j,8); height=eta+abs(x)
 assert (abs(x) if x>=0 else -abs(x))==x
 assert height==abs(x)+eta
print('Trace-ray check: 65 rational points regenerated from one trace vertex and two exact recession rays.')
w=list(map(F,I['group_weights']));tc=list(map(F,I['group_trace_centers']));a=list(map(F,I['normal_radii']))
assert sum(w)==1
# Three independent quotient coordinate axes; each group's two endpoints cancel its normal.
endpoints=[]
for i in range(3):
 for sign in [-1,1]:
  pt=[tc[i],F(0),F(0),F(0)];pt[i+1]=sign*a[i]
  val=abs(tc[i]+sign*a[i])+a[i]
  endpoints.append((w[i]/2,pt,val))
center=[sum(alpha*pt[j] for alpha,pt,val in endpoints) for j in range(4)]
assert center[1:]==[0,0,0]
avg=sum(alpha*val for alpha,pt,val in endpoints)
assert avg>=sum(wi*abs(t) for wi,t in zip(w,tc))>=abs(center[0])
print('All-page barycenter check: 3 independent normal groups; shared trace center',str(center[0]),'Jensen margin',str(avg-abs(center[0])))
for d in I['atom_dimensions']:
 mass=0;nonzero=0
 for word in product(range(d),repeat=d):
  # A repeat restricts |x_j| to zero on the already-cut saturated kernel.
  term=0 if len(set(word))<d else 2**d
  mass+=term;nonzero+=int(term>0)
 assert nonzero==math.factorial(d) and mass==2**d*math.factorial(d)
 print(f'Saturated-coordinate recursion d={d}: {d**d} words, {nonzero} surviving permutations, raw mass {mass}.')
c1,c2=map(F,I['page_weights']);delta=F(I['delta']);rr=F(I['roof_radius'])
# xz page contributes h=|x|+|z|; yz page restriction |z| has zero top atom.
raw=8*c1; scaled=delta**2*raw;contact=-rr*scaled
assert raw==12 and scaled>0 and contact<0
print('Two-page raw example: weights',str(c1),str(c2),'unscaled atom',str(raw),'scaled atom',str(scaled),'contact',str(contact))
for n in range(1,I['shift_indices']+1):
 e=F(1,2**n);nex=e/2
 assert 6*nex==3*e<4*e and (4*e-6*nex)==e
print('Global shift intervals: 12 stages; next upper 3eta < current lower 4eta, gap eta.')
# Real heights on rational spatial cells [0,1],[1,2]: pair (a,b) means a+b*sqrt(2).
# Heights sqrt2,1+sqrt2,2+2sqrt2 have slopes 1,1+sqrt2.
heights=[(F(0),F(1)),(F(1),F(1)),(F(2),F(2))]
slopes=[tuple(heights[i+1][j]-heights[i][j] for j in range(2)) for i in range(2)]
assert slopes==[(1,0),(1,1)]
assert F(7,5)**2<2<F(3,2)**2
print('Symbolic real-height check: rational spatial break 1, exact slopes 1 and 1+sqrt(2); no slope rounding.')
print('PASS: all own finite exact checks. These are not continuum proofs.')
