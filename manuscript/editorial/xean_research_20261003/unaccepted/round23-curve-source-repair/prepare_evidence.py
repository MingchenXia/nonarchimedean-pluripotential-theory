#!/usr/bin/env python3
"""Read-only source extraction. LF is the only line separator used here."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'evidence'
OUT.mkdir(exist_ok=True)
SHARED = Path('/workspace/research/shared-sources')

def sha(data):
    return hashlib.sha256(data).hexdigest()

def write_json(name, value):
    (OUT / name).write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')

inventory = json.loads((OUT / 'input-inventory.json').read_text())
for item in inventory:
    data = Path(item['path']).read_bytes()
    assert sha(data) == item['sha256'], item['path']
    assert len(data) == item['bytes']
    assert len(data.split(b'\n')) == item['lf_lines']

canonical = {}
for tag, count in [('r16', 3), ('r17', 5), ('r21', 2)]:
    cache = json.loads((OUT / f'{tag}-canonical-notes.json').read_text())
    data = Path(cache['origin']).read_bytes()
    assert sha(data) == cache['sha256']
    original = json.loads(data)
    notes = original['campaign']['result']['notes']
    assert len(notes) == count
    entry = next(x for x in cache['entries'] if x['json_path'] == '/campaign/result/notes')
    assert entry['notes'] == notes
    canonical[tag] = {'origin': cache['origin'], 'sha256': cache['sha256'],
                      'json_pointer': '/campaign/result/notes', 'notes': notes}
write_json('canonical-predecessor-notes.json', canonical)

review = json.loads((OUT / 'round16-independent-review.json').read_text())
# Preserve the controlling review verbatim; no verdict is generated by this script.
write_json('review-preserved.json', review)
review_origin = Path('/workspace/research/campaigns/round-16/P06.2-curve-two-sign-regularization-review/run.json')
review_bytes = review_origin.read_bytes()
assert sha(review_bytes) == 'ea4aae3ceea3584152c3700d1de31cd07e4fe8d39097a1ef38c5209f25b686fc'
assert json.loads(review_bytes)['campaign']['result'] == review
write_json('review-origin.json', {'path': str(review_origin), 'sha256': sha(review_bytes),
                                'bytes': len(review_bytes), 'canonical_pointer': '/campaign/result',
                                'result_unchanged': True})

definitions = [
    ('vdp-field-and-theorem-1.1', 'van-der-Put-AIF-1980-30-4-155.txt', 42, 221,
     r'^    The field k is supposed', r'^  End of the proof of 1\.1\.',
     'Field convention, Theorem 1.1, its complete proof including Lemma 1.2 and the final paragraph.'),
    ('berkovich-domain-comparison', 'Berkovich-PMIHES-1993-78-5.txt', 1335, 1438,
     r'^1\.6\. Connection', r'^space X\.',
     'Theorem 1.6.1 and Lemma 1.6.2 with complete selected proofs; following topos corollaries excluded.'),
    ('thuillier-semista-dirichlet', 'Thuillier-tel-00010990v1.txt', 3368, 3419,
     r'^Théorème 2\.3\.8\.', r'on lusion dé oule de la proposition 2\.3\.2',
     'Theorem 2.3.8 and Lemma 2.3.9, full selected statement/proof units, including intervening definition.'),
    ('thuillier-inserting-points', 'Thuillier-tel-00010990v1.txt', 2791, 2856,
     r'^Lemme 2\.2\.22\.', r'Toutes les extensions',
     'Lemma 2.2.22 and its complete proof. Type 2 versus type 3 distinction retained.'),
    ('thuillier-unit-slopes', 'Thuillier-tel-00010990v1.txt', 2897, 2999,
     r'^Proposition 2\.2\.24\.', r'λξ \(F \) = n',
     'Proposition 2.2.24 and Lemma 2.2.25 with complete proofs and their exact formal-model hypotheses.'),
    ('thuillier-residual-germ', 'Thuillier-tel-00010990v1.txt', 3626, 3700,
     r'^Lemme 2\.3\.22\.', r'preuve du lemme',
     'Lemma 2.3.22 and full proof. Context: preceding reduction to a proper geometrically connected residual component.'),
    ('thuillier-lisse-characterization', 'Thuillier-tel-00010990v1.txt', 4148, 4175,
     r'^Proposition 3\.2\.4\.', r'fon tion ontinue Φ est bien',
     'Proposition 3.2.4 with full proof; lisse is not ordinary CLD smooth.'),
    ('wanner-comparison', 'Wanner-1801.04713v3.txt', 991, 1608,
     r'^Lemma 4\.6\.', r'Step 0 proving the theo-',
     'Lemma 4.6 and Theorem 4.7, complete selected proofs; mathematical uses still require the cited model foundations.'),
]

records = []
blocks = []
for label, file, first, last, start, ending, description in definitions:
    path = SHARED / file
    data = path.read_bytes()
    lines = data.decode('utf-8').split('\n')
    selected = lines[first-1:last]
    assert re.search(start, selected[0]), (label, 'start', selected[0])
    assert any(re.search(ending, line) for line in selected[-12:]), (label, 'ending', selected[-12:])
    body = '\n'.join(selected) + '\n'
    records.append({'id': label, 'source': str(path), 'source_sha256': sha(data),
                    'source_bytes': len(data), 'source_lf_lines': len(lines),
                    'first_lf_line': first, 'last_lf_line': last,
                    'body_sha256': sha(body.encode()), 'description': description,
                    'selection_is_full_printed_proof_unit': True,
                    'nested_references_not_proved_by_extraction': True})
    blocks.append(f'## {label}\n\n{description}\n\nSource: `{path}`. SHA-256 `{sha(data)}`. '
                  f'LF lines {first}–{last}; selected-body SHA-256 `{sha(body.encode())}`. '
                  'Raw cached extraction follows; OCR/control characters are preserved. '
                  'This is evidence, not an accepted theorem application.\n\n```text\n' + body + '```\n')
write_json('source-selections.json', records)
(OUT / 'selected-primary-bodies.md').write_text('\n'.join(blocks))

core = Path('/workspace/research/campaigns/round-17/P06.2-recognition-source-proof-repair/artifacts/codex-qg6o2s')
cld16 = Path('/workspace/research/campaigns/round-16/P06.2-curve-two-sign-regularization-continuation/artifacts/codex-KSvMcT/sources')
cld21 = Path('/workspace/research/campaigns/round-21/P06.2-all-dimensional-completed-algebraic-continuation/artifacts/codex-ZwIWCf/sources')
comparisons = {'requested_proof_core_exists': (core / 'proof-core.md').exists(),
               'actual_repair_core': str(core / 'repair-core.md'),
               'actual_repair_core_sha256': sha((core / 'repair-core.md').read_bytes()),
               'CLD_pdf16_sha256': sha((cld16 / 'CLD.pdf').read_bytes()),
               'CLD_pdf21_sha256': sha((cld21 / 'CLD-v2.pdf').read_bytes()),
               'CLD_text16_sha256': sha((cld16 / 'CLD.txt').read_bytes()),
               'CLD_text21_sha256': sha((cld21 / 'CLD-v2.txt').read_bytes()),
               'CLD_pdf_bytes_identical': (cld16 / 'CLD.pdf').read_bytes() == (cld21 / 'CLD-v2.pdf').read_bytes(),
               'CLD_text_bytes_identical': (cld16 / 'CLD.txt').read_bytes() == (cld21 / 'CLD-v2.txt').read_bytes(),
               'interpretation': 'Different text extractions of an identical cached PDF; no mathematical or PDF-version discrepancy inferred.'}
write_json('cache-comparisons.json', comparisons)

for name in ['completed-algebraic-corrected-primary-bodies.md',
             'semistable-reduction-20261004/Bosch-Lutkebohmert-1985-I-machine-ocr.txt',
             'semistable-reduction-20261004/root-source-check.json',
             'curve-source-authentication-20261004/repair-evidence-manifest.json']:
    p = SHARED / name
    data = p.read_bytes()
    inventory.append({'key': name, 'path': str(p), 'sha256': sha(data),
                      'bytes': len(data), 'lf_lines': len(data.split(b'\n'))})
write_json('complete-read-inputs.json', inventory)
print(json.dumps({'input_hashes_unchanged': True, 'canonical_note_counts': {k: len(v['notes']) for k,v in canonical.items()},
                  'selected_complete_units': len(records), 'line_separator': 'LF only',
                  'proof_core_filename_mismatch_recorded': True, 'CLD_cached_pdf_identical': comparisons['CLD_pdf_bytes_identical']}))
