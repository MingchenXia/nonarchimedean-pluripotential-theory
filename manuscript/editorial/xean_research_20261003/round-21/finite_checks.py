"""Exact finite diagnostics; these do not establish the analytic theorem.

Rerun: python diagnostics/finite_checks.py > diagnostics/output.json
Uses only the Python standard library and installed SymPy. No network.
"""
import itertools
import json
import platform
import sympy as sp


# Exterior generators: 0..n-1 prime and n..2n-1 double-prime.
# A bit-set monomial is zero on wedging with a repeated generator.
exterior = []
for n in range(1, 13):
    prime = list(itertools.combinations(range(n), n-1))
    double = list(itertools.combinations(range(n, 2*n), n-1))
    transverse = {n-1, 2*n-1}
    survivors = []
    for left in prime:
        for right in double:
            if not (set(left+right) & transverse):
                survivors.append((left, right))
    assert len(survivors) == 1
    assert survivors[0] == (tuple(range(n-1)), tuple(range(n, 2*n-1)))
    exterior.append({"n": n, "components": n*n,
                     "second_normal_cutoff_survivors": 1,
                     "killed_by_repeated_generators": n*n-1})

# Polynomial collar profile. Extended by zero it is C^3, not C^infinity;
# this tests scaling identities only, not the lemma's smooth-cutoff hypothesis.
s = sp.symbols('s', real=True)
chi = (1-s*s)**4
profiles = []
for coefficient_order in (0, 1):
    profile = sp.expand(sp.diff(chi*s**coefficient_order, s, 2))
    coeff_sum = sum(abs(c) for c in sp.Poly(profile, s).all_coeffs())
    profiles.append({
        "coefficient_order_at_W": coefficient_order,
        "second_derivative_profile": str(profile),
        "one_dimensional_TV_scale": f"delta^{coefficient_order-1}",
        "profile_nonzero": profile != 0,
        "TV_upper_bound_constant_from_coefficients": str(2*coeff_sum),
        "signed_profile_integral": str(sp.integrate(profile, (s, -1, 1))),
    })
    assert profile != 0
    assert sp.integrate(profile, (s, -1, 1)) == 0

# Actual unreduced finite algebra over F_2:
# field E=F_2[a]/(a^4+a+1), R=E[u]/u^3, group generated by coefficient Frobenius.
# Explicitly verify field inverses rather than treating an irreducibility label
# as a computation grant. Sixteen field elements and 4096 R-elements are small.
def field_mul(a, b):
    result = 0
    while b:
        if b & 1:
            result ^= a
        b >>= 1
        a <<= 1
        if a & 16:
            a ^= 0b10011
    return result


def field_pow(a, k):
    result = 1
    while k:
        if k & 1:
            result = field_mul(result, a)
        a = field_mul(a, a)
        k >>= 1
    return result


assert all(field_mul(a, field_pow(a, 14)) == 1 for a in range(1, 16))
assert all(field_pow(a, 16) == a for a in range(16))
assert field_pow(2, 2) != 2 and field_pow(2, 4) != 2 and field_pow(2, 8) != 2


def ring_mul(a, b):
    result = [0, 0, 0]
    for i in range(3):
        for j in range(3-i):
            result[i+j] ^= field_mul(a[i], b[j])
    return tuple(result)


def conjugate(a):
    return tuple(field_mul(c, c) for c in a)


def norm(a):
    result = (1, 0, 0)
    current = a
    for _ in range(4):
        result = ring_mul(result, current)
        current = conjugate(current)
    assert current == a
    return result


invariants = 0
unit_norms = 0
for element in itertools.product(range(16), repeat=3):
    if conjugate(element) == element:
        invariants += 1
        assert all(c in (0, 1) for c in element)
    if element[0]:
        value = norm(element)
        assert value[0] == 1 and all(c in (0, 1) for c in value)
        unit_norms += 1
assert invariants == 8 and unit_norms == 3840
u = (0, 1, 0)
assert ring_mul(u, u) != (0, 0, 0)
assert ring_mul(ring_mul(u, u), u) == (0, 0, 0)

output = {
    "classification": "exhaustive finite algebra/exterior diagnostics and exact symbolic scaling; not analytic verification",
    "python": platform.python_version(), "sympy": sp.__version__,
    "exterior_basis_checks": exterior,
    "collar_polynomial_profiles": profiles,
    "boundary_face_contact": "half-collar t>=0 gives the same scaling upper bound; the proof uses ambient W vanishing, not an interior intersection",
    "artinian_algebra": {
        "base": "F_2", "extension": "F_2[a]/(a^4+a+1)",
        "galois_order": 4, "unreduced_algebra": "E[u]/u^3",
        "dimension_over_base": 12, "length_over_E": 3,
        "all_elements_checked": 4096, "invariant_elements": invariants,
        "all_unit_norms_checked": unit_norms,
        "unit_norm_in_base_failures": 0,
        "nilpotence_index_of_u": 3,
        "example_norm_1_plus_a_u": norm((1, 2, 0)),
        "field_degree_is_zero_in_characteristic": True,
        "real_calibration_factor_would_be": 4,
    },
}
