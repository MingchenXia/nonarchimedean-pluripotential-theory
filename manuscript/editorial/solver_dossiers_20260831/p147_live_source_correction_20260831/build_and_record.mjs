// Compile only the source-correction paragraph and check the exact live diff.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root='/private/tmp/nappt_p071_20260827';
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const record=p=>{const b=fs.readFileSync(p);return {path:p,bytes:b.length,sha256:sha(b)};};
const read=n=>fs.readFileSync(path.join(here,n),'utf8');
if(fs.existsSync(path.join(here,'MANIFEST.json')))throw Error('Already frozen');
const snapshots=JSON.parse(read('ORIGINAL_SNAPSHOTS.json')).files;
for(const x of snapshots)if(sha(fs.readFileSync(x.snapshot))!==x.sha256)throw Error('Original snapshot changed');
const oldChapter=read('original_ch72_major_open_problems.tex');
const start=oldChapter.indexOf('There is also a sharper published big-class question hidden inside the first');
const end=oldChapter.indexOf('Two unchanged extensions are excluded by',start);
if(start<0||end<=start)throw Error('Chapter boundaries');
const expectedChapter=oldChapter.slice(0,start)+read('chapter_replacement.tex')+'\n'+oldChapter.slice(end);
const chapterPath=path.join(root,'manuscript/parts/part6/ch72_major_open_problems.tex');
const chapter=fs.readFileSync(chapterPath,'utf8');
if(chapter!==expectedChapter)throw Error('Unexpected chapter edit');
const inventoryPath=path.join(root,'manuscript/editorial/open_problem_atomic_inventory_20260824.md');
const originalInventory=read('original_open_problem_atomic_inventory_20260824.md');
const i0=originalInventory.indexOf('- **P14.7**');
const i1=originalInventory.indexOf('### `prob:frontier-zero-volume`',i0);
let expectedInventory=originalInventory.slice(0,i0)+read('inventory_replacement.md')+'\n'+originalInventory.slice(i1);
expectedInventory=expectedInventory.replace('**Literature cutoff:** 24 August 2026','**Literature cutoff:** 24 August 2026; targeted P14.7/P14.8 source update on 31 August 2026');
const inventory=fs.readFileSync(inventoryPath,'utf8');
if(inventory!==expectedInventory)throw Error('Unexpected inventory edit');
const bibPath=path.join(root,'manuscript/bibliography/NonArchimedean.bib');
const bib=fs.readFileSync(bibPath,'utf8');
if(bib!==read('original_NonArchimedean.bib')+'\n'+read('bibliography_addition.bib'))throw Error('Unexpected bibliography edit');
const atomCount=[...inventory.matchAll(/^- \*\*P[0-9.]+\*\*.*\[T[1-5]; open/gm)].length;
const problemCount=[...chapter.matchAll(/\\begin\{problem\}/g)].length;
if(atomCount!==51||problemCount!==14)throw Error('Inventory count changed');
const labels=s=>[...s.matchAll(/\\label\{([^}]+)\}/g)].map(m=>m[1]);
if(JSON.stringify(labels(chapter))!==JSON.stringify(labels(oldChapter)))throw Error('Label change');
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'nappt-p147-source-draft-20260831-'));
for(const n of ['main.tex','chapter_replacement.tex','bibliography_addition.bib'])fs.copyFileSync(path.join(here,n),path.join(scratch,n),fs.constants.COPYFILE_EXCL);
for(const [r,n] of [['manuscript/bibliography/ComplexGeometry.bib','ComplexGeometry.bib'],['manuscript/style/sgptalpha.bst','sgptalpha.bst']])fs.copyFileSync(path.join(root,r),path.join(scratch,n),fs.constants.COPYFILE_EXCL);
const commands=[['pdflatex',['-draftmode','-interaction=nonstopmode','-halt-on-error','main.tex']],['bibtex',['main']],['pdflatex',['-draftmode','-interaction=nonstopmode','-halt-on-error','main.tex']],['pdflatex',['-draftmode','-interaction=nonstopmode','-halt-on-error','main.tex']]];
const runs=[];
for(let i=0;i<commands.length;i++){
  const [tool,args]=commands[i];
  const r=spawnSync('/Library/TeX/texbin/'+tool,args,{cwd:scratch,encoding:'utf8',maxBuffer:5*1024*1024,timeout:60000});
  fs.writeFileSync(path.join(here,`run${i+1}.out`),(r.stdout??'')+(r.stderr??''),{flag:'wx'});
  runs.push({tool,args,exitCode:r.status});
  if(r.status!==0)throw Error('Draft build failure: '+tool);
}
for(const n of ['main.log','main.bbl','main.blg'])fs.copyFileSync(path.join(scratch,n),path.join(here,n),fs.constants.COPYFILE_EXCL);
const log=read('main.log');
const warnings=log.split('\n').filter(x=>/^!|Undefined control|(?:LaTeX|Package .*?) Warning:|Overfull \\[hv]box/.test(x));
const underfull=log.split('\n').filter(x=>/Underfull \\[hv]box/.test(x));
if(warnings.length||fs.existsSync(path.join(scratch,'main.pdf')))throw Error('Unexpected draft diagnostic or PDF');
const result={date:'2026-08-31',scope:'Source-only Chapter72 correction; no candidate promotion; no full-book or PDF build',scratch,runs,warnings,underfull,pdfProduced:false,atomCount,problemCount,labelsUnchanged:true,before:snapshots,after:[chapterPath,inventoryPath,bibPath].map(record)};
fs.writeFileSync(path.join(here,'VALIDATION.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
const files=fs.readdirSync(here).filter(n=>n!=='MANIFEST.json').sort().map(n=>({name:n,...record(path.join(here,n))}));
fs.writeFileSync(path.join(here,'MANIFEST.json'),JSON.stringify({date:'2026-08-31',status:'Frozen source-correction evidence; no new theorem acceptance',files},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({sourceCorrectionChecked:true,atomCount,problemCount,warnings,underfull,pdfProduced:false,manifest:record(path.join(here,'MANIFEST.json')),after:result.after},null,2));
